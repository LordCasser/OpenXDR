export type Locale = keyof typeof dicts
export type MsgKey = keyof (typeof dicts)['zh']
export type T = (key: MsgKey, vars?: Record<string, string | number>) => string

const I18nContext = createContext<{ locale: Locale; setLocale: (l: Locale) => void; t: T }>({
  locale: 'zh',
  setLocale: () => {},
  t: k => k,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() =>
    localStorage.getItem('locale') === 'en' ? 'en' : 'zh',
  )
  const set = (l: Locale) => {
    localStorage.setItem('locale', l)
    setLocale(l)
  }
  const t: T = (key, vars) => {
    let s: string = dicts[locale][key] ?? key
    for (const [k, v] of Object.entries(vars ?? {})) s = s.replace(`{${k}}`, String(v))
    return s
  }
  return <I18nContext.Provider value={{ locale, setLocale: set, t }}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
